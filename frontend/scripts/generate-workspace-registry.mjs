#!/usr/bin/env node
// Generates lib/workspace/registry.generated.ts by walking the actual
// Next.js file-based router (app/dashboard/(auth)/**/page.tsx) — the same
// "existing routing configuration" the App Router itself uses to resolve
// URLs to pages. This is what lets the Workspace framework support every
// screen automatically: adding a new page.tsx (and a nav entry pointing at
// it) is enough — nobody has to hand-register it here. Runs automatically
// before `next dev`/`next build` (see package.json's predev/prebuild).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const FRONTEND_ROOT = path.join(__dirname, "..");
const APP_AUTH_DIR = path.join(FRONTEND_ROOT, "app", "dashboard", "(auth)");
const OUTPUT_FILE = path.join(FRONTEND_ROOT, "lib", "workspace", "registry.generated.ts");

function toPosix(p) {
  return p.split(path.sep).join("/");
}

// `generateMetadata` is a Server-Component-only export (Next.js resolves it
// during its own server-side route render). The Workspace shell mounts pages
// via a direct client-side `next/dynamic` import so it can keep them alive
// across tab switches — but that import path makes Next treat the whole
// module as reachable from a Client Component boundary, which is invalid for
// a module exporting `generateMetadata`. These pages simply keep their normal
// Next.js routing (no Workspace tab) instead of being force-included and
// breaking the build; nothing about this list is hand-picked, it's whatever
// currently uses that export.
function isMountable(filePath) {
  const src = readFileSync(filePath, "utf8");
  if (/export\s+(async\s+function|function|const)\s+generateMetadata\b/.test(src)) return false;
  // A handful of routes are pure server-side passthroughs (their default
  // export calls next/navigation's `redirect()` and renders nothing else) —
  // there's no JSX return, so there's nothing for a Workspace tab to display,
  // and it doesn't type as a mountable component.
  if (/\bredirect\(/.test(src) && !/return\s*\(?\s*</.test(src)) return false;
  return true;
}

function walk(dir, segments) {
  const entries = readdirSync(dir, { withFileTypes: true });
  const routes = [];
  for (const entry of entries) {
    if (entry.isDirectory()) {
      // Private folders (leading `_`) are excluded from Next.js's router.
      // Dynamic segments (`[id]`) aren't addressable by a single static
      // import path, so they're excluded — menu-linked screens are always
      // static list/overview routes, never a bare `[id]` route.
      if (entry.name.startsWith("_") || entry.name.includes("[")) continue;
      routes.push(...walk(path.join(dir, entry.name), [...segments, entry.name]));
    } else if (entry.isFile() && (entry.name === "page.tsx" || entry.name === "page.ts")) {
      const filePath = path.join(dir, entry.name);
      if (isMountable(filePath)) {
        routes.push(segments);
      }
    }
  }
  return routes;
}

const routes = walk(APP_AUTH_DIR, []).sort((a, b) => a.join("/").localeCompare(b.join("/")));

const entries = routes.map((segs) => {
  const routePath = "/dashboard/" + segs.join("/");
  const importPath = `@/app/dashboard/(auth)/${toPosix(segs.join("/"))}/page`;
  return `  { path: ${JSON.stringify(routePath)}, Component: dynamic(() => import(${JSON.stringify(importPath)}), { ssr: false }) },`;
}).join("\n");

const content = `// AUTO-GENERATED by scripts/generate-workspace-registry.mjs — do not edit by hand.
// Regenerated on every \`npm run dev\` / \`npm run build\` (see package.json)
// from the real file-based routes under app/dashboard/(auth)/**/page.tsx.
import dynamic from "next/dynamic";

import type { WorkspaceModule } from "./registry";

export const GENERATED_WORKSPACE_MODULES: WorkspaceModule[] = [
${entries}
];
`;

writeFileSync(OUTPUT_FILE, content, "utf8");
console.log(`[workspace-registry] Generated ${routes.length} entries -> ${path.relative(FRONTEND_ROOT, OUTPUT_FILE)}`);
