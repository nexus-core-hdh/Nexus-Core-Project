// Standard PLM reports for an apparel / garment business — seeded for every company
// (scripts/seed-plm-standard-reports.ts) as ordinary, user-editable report definitions.
//
// Every entry only uses fields declared in report-sources.ts and goes through the same
// validation as a report saved from the designer. Filters marked `prompt` ask for their value
// when the report is opened (a blank answer means "no restriction"), so one definition serves
// any season, customer, date range, ...
import type { ReportDefinitionInput, ReportFilter } from './report-builder.service';

type Def = Omit<ReportDefinitionInput, 'filters'> & { filters?: Omit<ReportFilter, 'id'>[] };

const asc = (field: string) => ({ field, direction: 'asc' as const });
const desc = (field: string) => ({ field, direction: 'desc' as const });
const cols = (...fields: (string | [string, string] | { field: string; label?: string; total?: boolean })[]) =>
  fields.map((f) => (typeof f === 'string' ? { field: f } : Array.isArray(f) ? { field: f[0], label: f[1] } : f));
const total = (field: string, label?: string) => ({ field, total: true, ...(label ? { label } : {}) });
const ask = (field: string, operator: string) => ({ field, operator, prompt: true });
const is = (field: string, operator: string, value?: string, value2?: string) => ({ field, operator, ...(value ? { value } : {}), ...(value2 ? { value2 } : {}) });

const CLOSED_SAMPLE = [is('status', 'notEquals', 'completed'), is('status', 'notEquals', 'approved'), is('status', 'notEquals', 'rejected')];

